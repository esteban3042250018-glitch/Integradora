BEGIN;

-- Keep an append-only history of counter resets and reservations.
ALTER TABLE personalizacion.configuracion_folios
    DROP CONSTRAINT IF EXISTS configuracion_folios_id_configuracion_check;
ALTER TABLE personalizacion.configuracion_folios
    ALTER COLUMN id_configuracion TYPE integer;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'personalizacion'
          AND table_name = 'configuracion_folios'
          AND column_name = 'id_configuracion'
          AND is_identity = 'YES'
    ) THEN
        ALTER TABLE personalizacion.configuracion_folios
            ALTER COLUMN id_configuracion
            DROP DEFAULT;
        ALTER TABLE personalizacion.configuracion_folios
            ALTER COLUMN id_configuracion
            ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS personalizacion.configuracion_formato_folio (
    id_configuracion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    segmentos jsonb NOT NULL,
    digitos smallint NOT NULL DEFAULT 3,
    fuente_membrete varchar(100) NOT NULL DEFAULT 'Arial',
    tamano_membrete numeric(5, 2) NOT NULL DEFAULT 10,
    fecha_actualizacion timestamp without time zone NOT NULL
        DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_configuracion_digitos
        CHECK (digitos BETWEEN 1 AND 12),
    CONSTRAINT chk_configuracion_segmentos
        CHECK (jsonb_typeof(segmentos) = 'array'),
    CONSTRAINT chk_configuracion_tamano
        CHECK (tamano_membrete > 0 AND tamano_membrete <= 100)
);

ALTER TABLE personalizacion.configuracion_formato_folio
    ADD COLUMN IF NOT EXISTS anio_folio integer;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM information_schema.check_constraints
        WHERE constraint_schema = 'personalizacion'
          AND constraint_name = 'chk_configuracion_anio_folio'
    ) THEN
        ALTER TABLE personalizacion.configuracion_formato_folio
            ADD CONSTRAINT chk_configuracion_anio_folio
            CHECK (anio_folio IS NULL OR anio_folio BETWEEN 1000 AND 9999);
    END IF;
END
$$;

ALTER TABLE personalizacion.configuracion_formato_folio
    DROP CONSTRAINT IF EXISTS chk_configuracion_id;
ALTER TABLE personalizacion.configuracion_formato_folio
    ALTER COLUMN id_configuracion TYPE integer;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'personalizacion'
          AND table_name = 'configuracion_formato_folio'
          AND column_name = 'id_configuracion'
          AND is_identity = 'YES'
    ) THEN
        ALTER TABLE personalizacion.configuracion_formato_folio
            ALTER COLUMN id_configuracion
            DROP DEFAULT;
        ALTER TABLE personalizacion.configuracion_formato_folio
            ALTER COLUMN id_configuracion
            ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM information_schema.table_constraints
        WHERE constraint_schema = 'personalizacion'
          AND table_name = 'configuracion_formato_folio'
          AND constraint_type = 'PRIMARY KEY'
    ) THEN
        ALTER TABLE personalizacion.configuracion_formato_folio
            ADD CONSTRAINT configuracion_formato_folio_pkey
            PRIMARY KEY (id_configuracion);
    END IF;
END
$$;

DO $$
DECLARE
    sequence_name text;
    max_id bigint;
BEGIN
    sequence_name := pg_get_serial_sequence(
        'personalizacion.configuracion_folios', 'id_configuracion');
    SELECT COALESCE(MAX(id_configuracion), 0)
    INTO max_id
    FROM personalizacion.configuracion_folios;
    IF sequence_name IS NOT NULL THEN
        PERFORM setval(sequence_name, max_id + 1, false);
    END IF;

    sequence_name := pg_get_serial_sequence(
        'personalizacion.configuracion_formato_folio', 'id_configuracion');
    SELECT COALESCE(MAX(id_configuracion), 0)
    INTO max_id
    FROM personalizacion.configuracion_formato_folio;
    IF sequence_name IS NOT NULL THEN
        PERFORM setval(sequence_name, max_id + 1, false);
    END IF;
END
$$;

INSERT INTO personalizacion.configuracion_folios
    (siguiente_numero)
SELECT 1
WHERE NOT EXISTS (
    SELECT 1 FROM personalizacion.configuracion_folios
);

INSERT INTO personalizacion.configuracion_formato_folio
    (segmentos, digitos, fuente_membrete, tamano_membrete)
SELECT
    '[{"tipo":"texto","valor":"IPN"},{"tipo":"texto","valor":"CVDRD"},{"tipo":"numero","valor":""},{"tipo":"anio","valor":""}]'::jsonb,
    3,
    'Arial',
    10
WHERE NOT EXISTS (
    SELECT 1 FROM personalizacion.configuracion_formato_folio
);

-- Keep a single active letterhead. Correspondence tables are not altered.
CREATE UNIQUE INDEX IF NOT EXISTS membrete_unico_activo_idx
    ON personalizacion.membrete (estatus)
    WHERE estatus IS TRUE;

COMMIT;
