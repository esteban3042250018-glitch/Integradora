ORDEN = list(nx.topological_sort(G))
SUCC = {i: list(G.successors(i)) for i in ORDEN}

# FUNCIÓN CPM

def cpm(duraciones):
    res = {}

    # Pasada hacia adelante
    for i in ORDEN:
        es = max(
            (res[p]["EF"] for p in ACT[i]["pred"]),
            default=0
        )
        res[i] = {
            "ES": es,
            "EF": es + duraciones[i]
        }

    fin = max(v["EF"] for v in res.values())

    # Pasada hacia atrás
    for i in reversed(ORDEN):
        lf = min(
            (res[s]["LS"] for s in SUCC[i]),
            default=fin
        )
        ls = lf - duraciones[i]

        libre = min(
            (res[s]["ES"] for s in SUCC[i]),
            default=fin
        ) - res[i]["EF"]

        res[i].update(
            LS=ls,
            LF=lf,
            HT=ls-res[i]["ES"],
            HL=libre
        )

        for col in ("HT", "HL"):
            if abs(res[i][col]) < 1e-8:
                res[i][col] = 0.0

    # Ruta crítica representativa
    actual = max(
        (i for i in ORDEN if not SUCC[i]),
        key=lambda i: res[i]["EF"]
    )

    ruta = [actual]

    while ACT[actual]["pred"]:
        actual = max(
            ACT[actual]["pred"],
            key=lambda p: res[p]["EF"]
        )
        ruta.append(actual)

    return res, fin, list(reversed(ruta))

# FUNCIÓN MONTE CARLO

def monte_carlo(retrasos=None):
    retrasos = retrasos or {}
    rng = np.random.default_rng(SEMILLA)
    ef = {}

    for i in ORDEN:
        x = ACT[i]

        alfa = 1 + 4*(x["m"]-x["a"])/(x["b"]-x["a"])
        beta = 1 + 4*(x["b"]-x["m"])/(x["b"]-x["a"])

        d = x["a"] + (x["b"]-x["a"]) * rng.beta(
            alfa, beta, ITERACIONES
        )

        d += retrasos.get(i, 0)

        es = (
            np.maximum.reduce([ef[p] for p in x["pred"]])
            if x["pred"]
            else np.zeros(ITERACIONES)
        )

        ef[i] = es + d

    return np.maximum.reduce([
        ef[i] for i in ORDEN if not SUCC[i]
    ])

# CONVERTIR DURACIONES A FECHAS

def fecha_estimada(inicio, dias):
    faltan = math.ceil(dias - 1e-10)
    dia = inicio

    while faltan > 0:
        if dia.weekday() < 5:
            faltan -= 1
            if faltan == 0:
                break
        dia += timedelta(days=1)

    return dia.isoformat()

