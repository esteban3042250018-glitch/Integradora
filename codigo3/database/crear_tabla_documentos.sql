CREATE SCHEMA IF NOT EXISTS correspondencia;

CREATE TABLE IF NOT EXISTS correspondencia.oficios_documentos (
    folio TEXT PRIMARY KEY,
    ruta_archivo TEXT NOT NULL,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS correspondencia.folios_anuales (
    anio INTEGER PRIMARY KEY,
    ultimo_numero BIGINT NOT NULL CHECK (ultimo_numero >= 0)
);

CREATE TABLE IF NOT EXISTS correspondencia.borradores (
    folio TEXT PRIMARY KEY,
    usuario_id TEXT NOT NULL,
    usuario_nombre TEXT NOT NULL,
    asunto TEXT NOT NULL DEFAULT '',
    area_emisora TEXT NOT NULL DEFAULT '',
    recepcion TEXT NOT NULL DEFAULT '',
    cuerpo TEXT NOT NULL DEFAULT '',
    estado TEXT NOT NULL DEFAULT 'Borrador'
        CHECK (estado IN ('Borrador', 'Creado', 'PDF generado')),
    reservado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS borradores_usuario_estado_actualizado_idx
    ON correspondencia.borradores (usuario_id, estado, actualizado_en DESC);

CREATE TABLE IF NOT EXISTS correspondencia.notificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio TEXT NOT NULL,
    tipo TEXT NOT NULL,
    titulo TEXT NOT NULL,
    mensaje TEXT NOT NULL,
    creado_por TEXT NOT NULL DEFAULT 'sistema',
    creada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (folio, tipo)
);

CREATE TABLE IF NOT EXISTS correspondencia.notificaciones_leidas (
    notificacion_id BIGINT NOT NULL
        REFERENCES correspondencia.notificaciones(id) ON DELETE CASCADE,
    usuario_id TEXT NOT NULL,
    leida_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (notificacion_id, usuario_id)
);
